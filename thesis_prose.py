"""正文撰写引擎：把「数据 + 客户任务书素材」组织成各不相同的中文正文。

为什么需要这一层
----------------
只把数字填进固定句式，做出来的论文是同一个人的论文换了一组数字——
两份任务书不同，正文却一模一样。要真正做到「每人一份」，需要在三个层次上
都产生差异：

1. **语料层**  每个叙述位置准备多套写法，且变体之间换的是**论述角度**
   （从工程问题切入／从规范条文切入／从计算逻辑切入／从工程经验切入／
   从上下游关系切入），而不是同义词替换。同一位置 5 套、一章 5 个位置，
   单章就有上千种组合。
2. **素材层**  客户任务书里的工程概况、水文气象、工程地质段落，按主题
   归位到对应章节，去掉任务书口吻后真正写进正文。这部分是客户独有的。
3. **结构层**  小节怎么分、段落先讲什么后讲什么、哪些内容因为数据不具备
   而整段不写（例如地震烈度低于 6 度就不写抗震计算），由数据决定。

选词的随机性由 `Seed` 控制：种子取自任务书正文与参数，因此
**同一份任务书每次生成结果一致（可复现），不同任务书结果必然不同**。
"""
