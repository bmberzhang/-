def sents(text):
    """中文分句。保留句末标点。"""
    text = re.sub(r'\s+', '', text or '')
    if not text:
        return []
    parts = re.split(r'(?<=[。；！？])', text)
    return [p for p in (x.strip() for x in parts) if len(p) >= 8]


_HEAD_STRIP = [
    re.compile(r'^[（(][一二三四五六七八九十\d]+[)）]\s*'),
    re.compile(r'^[一二三四五六七八九十]+[、.．]\s*'),
    re.compile(r'^\d+(?:\.\d+)*[、.．]?\s*'),
    re.compile(r'^第[一二三四五六七八九十\d]+[、.．]\s*'),
]

_SPOKEN = [
    ('本任务书', '本设计'), ('任务书', '设计资料'), ('学生', '设计者'),
    ('要求完成', '需完成'), ('应完成', '需完成'),
    ('毕业设计任务书', '设计任务'), ('务必', '应'), ('必须', '应'),
    ('请', ''), ('我们将', '本次设计将'), ('本课题', '本设计'),
]


def rework(sent):
    """把任务书口吻的句子改成论文口吻。"""
    s = (sent or '').strip()
    for p in _HEAD_STRIP:
        s = p.sub('', s)
    for a, b in _SPOKEN:
        s = s.replace(a, b)
    s = re.sub(r'[，,]\s*$', '。', s)
    s = re.sub(r'。{2,}', '。', s)
    # 任务书常用「本工程」自我指代，论文里改为「本工程」保持不变，只统一空格
    s = re.sub(r'\s+', '', s)
    return s


def classify(section_list):
    """把任务书段落按主题归类，返回 {主题: [句子, ...]}。"""
    out = {}
    for raw in (section_list or []):
        for st in sents(raw):
            low = st.lower()
            best, hit = 'other', 0
            for key, kws in _TOPIC:
                c = sum(1 for k in kws if k.lower() in low)
                if c > hit:
                    best, hit = key, c
            out.setdefault(best, []).append(rework(st))
    return out


def take(bucket, k, exclude=()):
    """从归类结果里取 k 句，避开已经用过的。"""
    got = []
    for s in bucket:
        if len(got) >= k:
            break
        if any(s == e or s[:12] == e[:12] for e in exclude):
            continue
        got.append(s)
    return got


