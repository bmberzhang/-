def _f(P, k, d=0.0):
    v = P.get(k)
    if v in (None, ''):
        return d
    try:
        return float(re.sub(r'[^\d.\-]', '', str(v)) or d)
    except ValueError:
        return d


def features(P, R):
    """从参数与计算结果推断工程特征。每种特征会切换正文的写法。

    返回 dict，键即为各章生成器可用的开关。
    """
    f = {}
    inten = _f(P, 'seismicIntensity', 0)
    f['seismic'] = inten >= 6                      # 6 度及以上需抗震
    f['high_seismic'] = inten >= 7
    acc = _f(P, 'seismicAcceleration', 0)
    f['acc'] = acc

    bearing = _f(P, 'foundationBearing', 0)
    st = (R or {}).get('st') or {}
    f['foundation'] = True
    f['rebar'] = True          # 闸室结构必然配筋，引混凝土结构设计规范
    f['seepage'] = True
    f['stability'] = True
    f['energy'] = True
    f['construction'] = False  # 本次不编施工组织，不引该规范

    # 地基类型：软土／砂砾石／黏性土，决定基础处理写不写
    ftxt = str(P.get('foundationType') or '') + str(P.get('geologyDesc') or '')
    f['soft'] = any(k in ftxt for k in ('淤泥', '软土', '软黏', '软粘', '泥炭'))
    f['gravel'] = any(k in ftxt for k in ('砂砾', '卵石', '砂卵', '砾石'))
    f['clay'] = any(k in ftxt for k in ('黏土', '粘土', '粉质'))

    # 基底最大应力超承载力 → 必须写地基处理
    smax = (st.get('sigma_max') or 0)
    f['bearing_fail'] = bool(bearing) and smax > bearing
    f['need_treat'] = f['soft'] or f['bearing_fail']

    # 消能：池深是否为 0（全淹没）决定叙述重点
    en = (R or {}).get('en') or {}
    d_design = en.get('d_design', 0)
    f['no_pool'] = d_design <= 0.01                # 不需要消力池
    f['deep_pool'] = d_design >= 1.5

    # 渗流：实际渗径是否紧贴所需（裕度小于 10% 需提醒）
    sp = (R or {}).get('sp') or {}
    lact, lreq = sp.get('L_actual', 0), sp.get('L_required', 0)
    f['seep_tight'] = bool(lreq) and lact < lreq * 1.10
    f['seep_fail'] = bool(lreq) and lact < lreq

    # 稳定：抗滑是否紧贴允许值
    kc = st.get('Kc', 0)
    f['stab_tight'] = bool(kc) and kc < 1.25
    f['stab_fail'] = bool(kc) and kc < 1.20

    # 是否属除险加固（任务书里提到原闸／重建／安全鉴定）。
    # 注意「加固」单独出现多为「地基加固」，不能据此判定是加固工程，
    # 必须与「原闸／拆除／安全鉴定／病险」等词搭配才算。
    raw = str(P.get('_raw') or '') + str(P.get('projectName') or '')
    strong = ('原闸', '拆除重建', '安全鉴定', '除险加固', '病险', '重建工程',
              '老化', '四类闸', '破损严重', '拆除改建', '加固改造')
    f['rehab'] = any(k in raw for k in strong)
    # 是否多孔（影响闸门调度、检修的叙述）
    n = int(_f(P, 'gateCount', 3))
    f['multi_gate'] = n >= 3

    return f


