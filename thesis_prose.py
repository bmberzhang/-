def refs_for(seed, flags, n=10):
    """按工程特征挑选参考文献，不同工程得到不同列表。"""
    pool = [item for item, cond in REF_POOL
            if cond is None or flags.get(cond)]
    # 排在前面的是必备规范与教材，顺序固定；其余按种子打乱后取够条数
    fixed, rest = pool[:6], pool[6:]
    seed.order(rest)
    out = (fixed + rest)[:max(6, min(n, len(pool)))]
    res = []
    for i, r in enumerate(out, 1):
        res.append('[%d] %s' % (i, JOURNAL.get(r, r)))
    return res


